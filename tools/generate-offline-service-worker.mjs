#!/usr/bin/env node
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const dist = path.resolve(process.argv[2] ?? "apps/web/dist");
const rawBase = process.env.GITHUB_PAGES_BASE ?? process.env.BASE_URL ?? "/";
const base = `/${rawBase.replace(/^\/+|\/+$/g, "")}${rawBase === "/" ? "" : "/"}`.replace(/^\/\/$/, "/");

async function walk(directory, prefix = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.name === "sw.js") continue;
    const absolute = path.join(directory, entry.name);
    const relative = path.posix.join(prefix, entry.name);
    if (entry.isDirectory()) files.push(...await walk(absolute, relative));
    else if (entry.isFile() && !relative.endsWith(".map")) files.push(relative);
  }
  return files;
}

const files = (await walk(dist)).sort();
const digest = createHash("sha256");
for (const file of files) {
  digest.update(file);
  digest.update(await readFile(path.join(dist, file)));
}
const version = digest.digest("hex").slice(0, 12);
const urls = files.map((file) => `${base}${file}`.replace(/\/+/g, "/"));
const script = `/* generated by tools/generate-offline-service-worker.mjs */
const CACHE_NAME = "hero-language-camp-${version}";
const APP_BASE = ${JSON.stringify(base)};
const PRECACHE_URLS = ${JSON.stringify(urls)};

async function notifyClients(message) {
  const clientsList = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
  for (const client of clientsList) client.postMessage(message);
}

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    let completed = 0;
    let nextIndex = 0;
    const workerCount = Math.min(6, PRECACHE_URLS.length);
    const workers = Array.from({ length: workerCount }, async () => {
      while (nextIndex < PRECACHE_URLS.length) {
        const url = PRECACHE_URLS[nextIndex++];
        const response = await fetch(url, { cache: "reload" });
        if (!response.ok) throw new Error("Offline download failed: " + url + " (" + response.status + ")");
        await cache.put(url, response);
        completed += 1;
        await notifyClients({ type: "OFFLINE_PROGRESS", completed, total: PRECACHE_URLS.length });
      }
    });
    await Promise.all(workers);
    await notifyClients({ type: "OFFLINE_INSTALLED", total: PRECACHE_URLS.length, version: CACHE_NAME });
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((name) => name.startsWith("hero-language-camp-") && name !== CACHE_NAME).map((name) => caches.delete(name)));
    await self.clients.claim();
    await notifyClients({ type: "OFFLINE_READY", version: CACHE_NAME });
  })());
});

self.addEventListener("message", (event) => {
  if (event.data?.type === "SKIP_WAITING") self.skipWaiting();
  if (event.data?.type === "GET_OFFLINE_STATUS") {
    event.source?.postMessage({ type: "OFFLINE_READY", version: CACHE_NAME });
  }
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const requestUrl = new URL(event.request.url);
  if (requestUrl.origin !== self.location.origin || !requestUrl.pathname.startsWith(APP_BASE)) return;

  event.respondWith((async () => {
    const cache = await caches.open(CACHE_NAME);
    const cached = await cache.match(event.request, { ignoreSearch: false });
    if (cached) return cached;
    try {
      const response = await fetch(event.request);
      if (response.ok) await cache.put(event.request, response.clone());
      return response;
    } catch (error) {
      if (event.request.mode === "navigate") {
        const fallback = await cache.match(APP_BASE + "index.html") || await cache.match(APP_BASE);
        if (fallback) return fallback;
      }
      throw error;
    }
  })());
});
`;
await writeFile(path.join(dist, "sw.js"), script, "utf8");
console.log(`Generated offline service worker ${version} with ${files.length} files at base ${base}`);
